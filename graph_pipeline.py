x, train_pos_edge_index = data.x.to(device), data.train_pos_edge_index.to(device)
optimizer = torch.optim.Adam(model.parameters(), lr=0.01)

def get_link_labels(pos_edge_index, neg_edge_index):
    pos_label = torch.ones(pos_edge_index.size(1))
    neg_label = torch.zeros(neg_edge_index.size(1))
    return torch.cat([pos_label, neg_label]).to(device)

