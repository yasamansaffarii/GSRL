context_size = 5
epochs = 5
learning_rate = 0.01
window_size = context_size

# ===================== Random Walk Generator =====================
def generate_random_walk(graph, start_node, walk_length):
    walk = [start_node]
    for _ in range(walk_length - 1):
        neighbors = list(graph.neighbors(walk[-1]))
        if neighbors:
            walk.append(random.choice(neighbors))
        else:
            break
    return walk

all_walks = []
for _ in range(num_walks):
    for node in G_fixed.nodes():
        walk = generate_random_walk(G_fixed, node, walk_length)
        all_walks.append([node2id[n] for n in walk])

# ===================== Generate (center, context) pairs =====================
def generate_skipgram_pairs(walks, window_size):
    pairs = []
    for walk in walks:
        for i in range(len(walk)):
            for j in range(max(0, i - window_size), min(len(walk), i + window_size + 1)):
                if i != j:
                    pairs.append((walk[i], walk[j]))
    return pairs

pairs = generate_skipgram_pairs(all_walks, window_size)

# ===================== PyTorch Model =====================
class Node2Vec(nn.Module):
    def __init__(self, num_nodes, embedding_dim):
        super().__init__()
        self.embeddings = nn.Embedding(num_nodes, embedding_dim)

    def forward(self, center_nodes):
        return self.embeddings(center_nodes)

model = Node2Vec(num_nodes, embedding_dim)
optimizer = optim.Adam(model.parameters(), lr=learning_rate)
loss_fn = nn.CrossEntropyLoss()

# ===================== Training =====================
for epoch in range(epochs):
    total_loss = 0
    random.shuffle(pairs)
    for center, context in tqdm(pairs, desc=f"Epoch {epoch+1}"):
        center_tensor = torch.tensor([center], dtype=torch.long)
        context_tensor = torch.tensor([context], dtype=torch.long)

        logits = model(center_tensor) @ model.embeddings.weight.T  # Dot product
        loss = loss_fn(logits, context_tensor)

        optimizer.zero_grad()
        loss.backward()
        optimizer.step()

        total_loss += loss.item()

