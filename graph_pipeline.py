node_ids = []

for node in G_nx.nodes:
    feat = G_nx.nodes[node].get("feat", None)
    if feat is None:
        raise ValueError(f"Node {node} has no feature!")
    node_feats.append(feat)
    node_ids.append(node)

x_tensor = torch.tensor(np.array(node_feats), dtype=torch.float32)

# 3. Convert to PyG Data object
data = from_networkx(G_nx)
data.x = x_tensor
data = train_test_split_edges(data)  # removes edge_index from data

# 4. Define GraphSAGE model
class GraphSAGE(nn.Module):
    def __init__(self, in_channels, hidden_channels):
        super(GraphSAGE, self).__init__()
        self.conv1 = SAGEConv(in_channels, hidden_channels)
        self.conv2 = SAGEConv(hidden_channels, hidden_channels)

    def encode(self, x, edge_index):
        x = self.conv1(x, edge_index)
        x = F.relu(x)
        x = self.conv2(x, edge_index)
        return x

    def decode(self, z, edge_index):
        return (z[edge_index[0]] * z[edge_index[1]]).sum(dim=1)

    def decode_all(self, z):
        return torch.matmul(z, z.t())

